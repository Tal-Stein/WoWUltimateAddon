local ns = __ns

__boot(nil, {})
local G = ns.Grades

describe("Grades", function()
  it("estimates seconds for kills and travel", function()
    assertEq(G.estimateSeconds({ objectives = { { kind = "kill", count = 10, level = 10 } }, zones = 1 }, 10), 340)
  end)
  it("turns a drop rate into kills", function()
    assertEq(G.estimateSeconds({ objectives = { { kind = "drop", count = 10, rate = 31, level = 10 } }, zones = 1 }, 10), 915)
  end)
  it("doesn't guess an unknown count", function()
    assertNil(G.estimateSeconds({ objectives = { { kind = "kill", level = 10 } }, zones = 1 }, 10))
  end)
  it("doesn't guess an unknown drop rate", function()
    assertNil(G.estimateSeconds({ objectives = { { kind = "drop", count = 10, level = 10 } }, zones = 1 }, 10))
  end)
  it("costs higher-level elites more", function()
    assertEq(G.estimateSeconds({ objectives = { { kind = "kill", count = 2, level = 12, elite = true } }, zones = 1 }, 10), 300)
  end)
  it("adds time per extra zone and per object", function()
    assertEq(G.estimateSeconds({ objectives = { { kind = "object", count = 3 } }, zones = 3 }, 10), 30 + 90 + 240)
  end)
  it("bands leveling by XP per minute against the baseline", function()
    assertEq(G.levelingFixed(40, 100), 1)
    assertEq(G.levelingFixed(79, 100), 2)
    assertEq(G.levelingFixed(100, 100), 3)
    assertEq(G.levelingFixed(150, 100), 4)
    assertEq(G.levelingFixed(200, 100), 5)
    assertNil(G.levelingFixed(nil, 100))
    assertNil(G.levelingFixed(100, 0))
  end)
  it("bands gear by upgrade size", function()
    assertEq(G.gearFixed(110, 100), 3)
    assertEq(G.gearFixed(100, 100), "none")
    assertEq(G.gearFixed(50, 0), 5)
    assertNil(G.gearFixed(nil, 100))
    assertEq(G.gearFixed(102, 100), 1)
  end)
  it("ranks relative to the other options", function()
    assertEq(G.relative(5, { 1, 5, 9 }), 3)
    assertEq(G.relative(9, { 1, 5, 9 }), 5)
    assertEq(G.relative(1, { 1, 5, 9 }), 1)
    assertEq(G.relative(4, { 4 }), 3)
    assertNil(G.relative(nil, { 1 }))
  end)
  it("combines weighted factors, skipping unknown ones", function()
    assertEq(G.unifiedScore({ speed = 1, gear = 0 }, { speed = 50, gear = 50 }), 0.5)
    assertEq(G.unifiedScore({ speed = 1 }, { speed = 50, gear = 50 }), 1)
    assertNil(G.unifiedScore({ speed = 1 }, { speed = 0 }))
  end)
  it("maps a unified score to 1-5", function()
    assertEq(G.unifiedFixed(0), 1)
    assertEq(G.unifiedFixed(0.5), 3)
    assertEq(G.unifiedFixed(1), 5)
  end)
  it("ships three presets", function()
    assertEq(G.PRESETS.balanced.speed, 60)
    assertEq(G.PRESETS.speed.speed, 100)
    assertEq(G.PRESETS.gear.gear, 100)
  end)
end)
