local FT = __ns.FlightTime

describe("Flight time lookup", function()
  local data = { [1] = { [2] = 100, [3] = 300 }, [2] = { [4] = 50 } }

  it("uses the direct time from the source to the destination", function()
    assertEq(FT.Route({ data }, 1, 3), 300)
  end)
  it("falls back to the reverse flight", function()
    assertEq(FT.Route({ data }, 3, 1), 300)
  end)
  it("prefers an earlier table (your own flights) over a later one", function()
    local mine = { [1] = { [3] = 280 } }
    assertEq(FT.Route({ mine, data }, 1, 3), 280)
  end)
  it("prefers any table's direct time over a reverse time", function()
    local mine = { [3] = { [1] = 290 } }
    assertEq(FT.Route({ mine, data }, 1, 3), 300)
  end)
  it("adds up the legs when the whole route isn't known", function()
    assertEq(FT.Route({ data }, 1, 4, { { 1, 2 }, { 2, 4 } }), 150)
  end)
  it("knows nothing when a leg is missing", function()
    assertNil(FT.Route({ data }, 1, 9, { { 1, 2 }, { 2, 9 } }))
  end)
  it("knows nothing without both ends", function()
    assertNil(FT.Route({ data }, nil, 3))
    assertNil(FT.Route({ data }, 1, nil))
  end)
end)

describe("Flight time format", function()
  it("shows minutes and seconds", function()
    assertEq(FT.Format(151), "2:31")
    assertEq(FT.Format(5), "0:05")
  end)
  it("shows hours for long flights", function()
    assertEq(FT.Format(3725), "1:02:05")
  end)
  it("rounds up partial seconds and never goes below zero", function()
    assertEq(FT.Format(150.2), "2:31")
    assertEq(FT.Format(-3), "0:00")
  end)
end)
