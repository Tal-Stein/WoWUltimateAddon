local ns = __ns
local Macro = ns.Macro

describe("Macro.build", function()
  it("test_macro_basic", function()
    local text = Macro.build({ "A", "B", "C" }, 1, { stopInCombat = true, fallbacks = 2, marker = 0 })
    assertEq(text, "/stopmacro [combat,exists,harm,nodead]\n/cleartarget [dead][help]\n/targetexact A\n/targetexact [noexists] B\n/targetexact [noexists] C")
  end)
  it("test_macro_cursor_wraps", function()
    local text = Macro.build({ "A", "B", "C" }, 3, { stopInCombat = false, fallbacks = 2, marker = 0 })
    assertEq(text, "/cleartarget [dead][help]\n/targetexact C\n/targetexact [noexists] A\n/targetexact [noexists] B")
  end)
  it("adds the raid marker line", function()
    local text = Macro.build({ "A" }, 1, { stopInCombat = false, fallbacks = 2, marker = 8 })
    assertEq(text, "/cleartarget [dead][help]\n/targetexact A\n/tm [exists,harm,nodead] !8")
  end)
  it("test_macro_budget_and_sanitise", function()
    local names = {}
    for i = 1, 5 do names[i] = string.rep(string.char(64 + i), 60) end
    names[1] = names[1] .. ";/run Evil()"
    local text = Macro.build(names, 1, { stopInCombat = true, fallbacks = 4, marker = 8 })
    assertTrue(#text <= 255, "within 255 bytes, got " .. #text)
    assertTrue(text:find("/targetexact " .. string.rep("A", 60) .. "run Evil()", 1, true) ~= nil, "primary line present and sanitised")
    assertTrue(text:find(";", 1, true) == nil, "no injected separator")
    assertTrue(text:find("/tm", 1, true) ~= nil, "marker kept, fallbacks dropped first")
  end)
  it("drops the marker before the primary line", function()
    local long = string.rep("Z", 200)
    local text = Macro.build({ long }, 1, { stopInCombat = true, fallbacks = 2, marker = 8 })
    assertTrue(#text <= 255)
    assertTrue(text:find("/targetexact " .. long, 1, true) ~= nil)
  end)
  it("test_macro_empty_list", function()
    assertEq(Macro.build({}, 1, { stopInCombat = true, fallbacks = 2, marker = 8 }), "/cleartarget [dead]")
  end)
end)

describe("Macro.Cursor", function()
  it("test_cursor_advances_and_resets", function()
    local cur = Macro.Cursor.new()
    cur:set({ "A", "B", "C" })
    assertEq(cur:current(), 1)
    assertFalse(cur:onTargetName("B"), "only the cursor's name advances")
    assertTrue(cur:onTargetName("A"))
    assertEq(cur:current(), 2)
    cur:onTargetName("B"); cur:onTargetName("C")
    assertEq(cur:current(), 1, "wraps around")
    cur:onTargetName("A")
    cur:set({ "A", "B", "C" })
    assertEq(cur:current(), 2, "same top keeps position")
    cur:set({ "X", "A" })
    assertEq(cur:current(), 1, "new top resets")
    cur:set({ "Solo" })
    assertFalse(cur:onTargetName("Solo"), "single name never advances")
    assertEq(cur:current(), 1)
  end)
  it("clamps when the list shrinks", function()
    local cur = Macro.Cursor.new()
    cur:set({ "A", "B", "C" })
    cur:onTargetName("A"); cur:onTargetName("B")
    cur:set({ "A", "B" })
    assertEq(cur:current(), 1)
    cur:reset()
    assertEq(cur:current(), 1)
  end)
end)
