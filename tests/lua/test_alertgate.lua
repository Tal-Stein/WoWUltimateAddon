local ns = __ns

describe("AlertGate", function()
  it("test_alertgate", function()
    local gate = ns.AlertGate.new({ guidCooldown = 60, nameCooldown = 10 })
    assertTrue(gate:shouldAlert("g1", "Kobold", 0))
    assertFalse(gate:shouldAlert("g1", "Kobold", 30), "same GUID within 60s")
    assertFalse(gate:shouldAlert("g2", "Kobold", 5), "same name within 10s")
    assertTrue(gate:shouldAlert("g3", "Kobold", 16), "name cooldown expired (last alert at 0)")
    assertFalse(gate:shouldAlert("g1", "Kobold", 50), "g1 still on cooldown")
    assertTrue(gate:shouldAlert("g1", "Kobold", 61), "g1 expired, name last at 16 > 10s ago")
  end)
  it("prunes old entries", function()
    local gate = ns.AlertGate.new({ guidCooldown = 60, nameCooldown = 10 })
    gate:shouldAlert("g1", "A", 0)
    gate:prune(100)
    assertNil(next(gate.byGuid))
    assertNil(next(gate.byName))
  end)
  it("updates cooldowns from options", function()
    local gate = ns.AlertGate.new({ guidCooldown = 60, nameCooldown = 10 })
    gate:shouldAlert("g1", "A", 0)
    gate:configure({ guidCooldown = 5, nameCooldown = 0 })
    assertTrue(gate:shouldAlert("g1", "A", 6))
  end)
end)
